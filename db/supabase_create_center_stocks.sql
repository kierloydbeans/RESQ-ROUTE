-- Create evacuation center stocks table
-- Run this in Supabase SQL Editor

-- 1. Create the table
CREATE TABLE IF NOT EXISTS center_stocks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id INTEGER NOT NULL REFERENCES center(id) ON DELETE CASCADE,
    item_description TEXT NOT NULL,
    current_stock INTEGER NOT NULL DEFAULT 0,
    max_stock INTEGER DEFAULT 1000,
    unit TEXT DEFAULT 'units',
    status TEXT DEFAULT 'OK'
        CHECK (status IN ('OK', 'LOW', 'CRITICAL')),
    last_shipment TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Create index for faster queries by center
CREATE INDEX IF NOT EXISTS idx_center_stocks_center_id
    ON center_stocks(center_id);

-- 3. Create index for filtering by status
CREATE INDEX IF NOT EXISTS idx_center_stocks_status
    ON center_stocks(status);

-- 4. Enable Row Level Security (RLS)
ALTER TABLE center_stocks ENABLE ROW LEVEL SECURITY;

-- 5. Create policies for access

-- Allow public read access
CREATE POLICY "Enable read access for all users"
    ON center_stocks
    FOR SELECT
    USING (true);

-- Allow authenticated users to insert
CREATE POLICY "Enable insert for authenticated users"
    ON center_stocks
    FOR INSERT
    WITH CHECK (auth.role() = 'authenticated');

-- Allow authenticated users to update
CREATE POLICY "Enable update for authenticated users"
    ON center_stocks
    FOR UPDATE
    USING (auth.role() = 'authenticated');

-- Allow authenticated users to delete
CREATE POLICY "Enable delete for authenticated users"
    ON center_stocks
    FOR DELETE
    USING (auth.role() = 'authenticated');

