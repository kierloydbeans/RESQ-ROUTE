-- 7. Create a view for easier querying with center name
CREATE OR REPLACE VIEW center_stocks_with_center AS
SELECT
    cs.id,
    cs.center_id,
    c.name AS center_name,
    c.address AS center_address,
    cs.item_description,
    cs.current_stock,
    cs.max_stock,
    cs.unit,
    cs.status,
    cs.last_shipment,
    cs.created_at,
    cs.updated_at
FROM center_stocks cs
JOIN center c ON cs.center_id = c.id;

